using System.ComponentModel.DataAnnotations;

namespace StangaNetLib.Auth.Settings;

/// <summary>Configuration for TOTP (RFC 6238) multi-factor authentication.</summary>
public sealed class TotpSettings
{
    /// <summary>Configuration section name. Value: <c>"TotpSettings"</c>.</summary>
    public const string SectionName = "TotpSettings";

    /// <summary>Issuer label shown in authenticator apps. Default: <c>"StangaNet"</c>.</summary>
    [Required]
    public string Issuer { get; set; } = "StangaNet";

    /// <summary>Allowed time-step drift on either side of the current window. Default: 1.</summary>
    [Range(0, 5)]
    public int VerificationWindow { get; set; } = 1;

    /// <summary>Number of one-time recovery codes generated by default. Default: 10.</summary>
    [Range(4, 32)]
    public int RecoveryCodeCount { get; set; } = 10;

    /// <summary>Length of each recovery code (alphanumeric). Default: 10.</summary>
    [Range(8, 32)]
    public int RecoveryCodeLength { get; set; } = 10;
}
